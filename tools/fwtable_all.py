#!/usr/bin/env python3
"""Offset tables for TopazModem (sunstone) from a dump of the stock modem_a partition (FAT16).

  python3 tools/fwtable_all.py out/modem_a.img > tables.inc

Prints three C tables with byte offsets inside the partition:
  fw_files[]  modem.mdt + modem.bNN: {name, off, size, crc32} (one extent each, checked)
  fw_ext[]    every extent (run of contiguous clusters) of every file
  fw_all[]    every file, lower-case path relative to the root: {path, size, ext, next}
Also prints the modem.mdt program headers as a comment (carveout check in modem_boot()).
"""
import struct
import sys
import zlib


def main():
    path = sys.argv[1]
    img = open(path, 'rb').read()
    bps, spc, rsv, nfats, nroot, tot16, _media, fatsz = struct.unpack_from('<HBHBHHBH', img, 11)
    tot = tot16 or struct.unpack_from('<I', img, 32)[0]
    clus = bps * spc
    fat_off = rsv * bps
    root_off = fat_off + nfats * fatsz * bps
    data_off = root_off + nroot * 32
    fat = img[fat_off:fat_off + fatsz * bps]
    nclus = (tot * bps - data_off) // clus + 2
    if nclus >= 65525 or nclus < 4085:
        sys.exit('not FAT16 (%d clusters)' % nclus)

    def chain(c):
        out = []
        while 2 <= c < 0xfff8:
            out.append(c)
            c = struct.unpack_from('<H', fat, 2 * c)[0]
        return out

    def coff(c):
        return data_off + (c - 2) * clus

    def entries(raw):
        lfn = {}
        for i in range(0, len(raw), 32):
            e = raw[i:i + 32]
            if e[0] == 0:
                break
            if e[0] == 0xe5:
                lfn = {}
                continue
            attr = e[11]
            if attr == 0x0f:
                seq = e[0] & 0x1f
                part = (e[1:11] + e[14:26] + e[28:32]).decode('utf-16-le', 'replace')
                lfn[seq] = part.split('\x00')[0]
                continue
            if attr & 0x08:
                lfn = {}
                continue
            if lfn:
                name = ''.join(lfn[k] for k in sorted(lfn))
            else:
                base = e[0:8].decode('ascii', 'replace').rstrip()
                ext = e[8:11].decode('ascii', 'replace').rstrip()
                if e[12] & 0x08:
                    base = base.lower()
                if e[12] & 0x10:
                    ext = ext.lower()
                name = base + ('.' + ext if ext else '')
            lfn = {}
            if name in ('.', '..'):
                continue
            first = struct.unpack_from('<H', e, 26)[0]
            size = struct.unpack_from('<I', e, 28)[0]
            yield name, attr, first, size

    files = []

    def walk(raw, prefix):
        for name, attr, first, size in entries(raw):
            p = prefix + name
            if attr & 0x10:
                sub = b''.join(img[coff(c):coff(c) + clus] for c in chain(first))
                walk(sub, p + '/')
            else:
                cl = chain(first) if size else []
                need = (size + clus - 1) // clus
                cl = cl[:need]
                ext = []
                for c in cl:
                    if ext and ext[-1][0] + ext[-1][1] == coff(c):
                        ext[-1][1] += clus
                    else:
                        ext.append([coff(c), clus])
                left = size
                for x in ext:
                    x[1] = min(x[1], left)
                    left -= x[1]
                files.append((p.lower(), size, ext))

    walk(img[root_off:data_off], '')
    files.sort(key=lambda f: f[0])

    def data(f):
        return b''.join(img[o:o + l] for o, l in f[2])

    print('/* generated by tools/fwtable_all.py from %s: %d files, %d extents */' %
          (path.split('/')[-1], len(files), sum(len(f[2]) for f in files)))

    # modem.mdt program headers
    mdt = [f for f in files if f[0] == 'image/modem.mdt']
    if mdt:
        d = data(mdt[0])
        phoff, = struct.unpack_from('<I', d, 28)
        phentsize, phnum = struct.unpack_from('<HH', d, 42)
        lo, hi = 1 << 64, 0
        print('/* modem.mdt: %d program headers' % phnum)
        for i in range(phnum):
            t, off, va, pa, fsz, msz, fl, al = struct.unpack_from('<8I', d, phoff + i * phentsize)
            print(' *  %2d type %x off %08x paddr %08x filesz %08x memsz %08x flags %08x' %
                  (i, t, off, pa, fsz, msz, fl))
            if t == 1 and (fl & (7 << 24)) != (2 << 24) and msz:
                lo, hi = min(lo, pa), max(hi, pa + msz)
        print(' *  PT_LOAD range %08x-%08x (%#x bytes)' % (lo, hi, hi - lo))
        print(' */')

    print('static const struct { const char *name; uint32_t off, size, crc; } fw_files[] = {')
    for f in files:
        n = f[0].split('/')[-1]
        if f[0].startswith('image/modem.') and (n == 'modem.mdt' or n[6:7] == 'b'):
            if len(f[2]) != 1:
                sys.exit('%s is fragmented' % f[0])
            print('\t{ "%s", %#x, %#x, 0x%08x },' % (n, f[2][0][0], f[1], zlib.crc32(data(f)) & 0xffffffff))
    print('};')
    print()
    print('static const struct { uint32_t off, len; } fw_ext[] = {')
    for f in files:
        for o, l in f[2]:
            print('\t{ %#x, %#x },' % (o, l))
    print('};')
    print('static const struct { const char *path; uint32_t size; uint16_t ext, next; } fw_all[] = {')
    k = 0
    for f in files:
        print('\t{ "%s", %#x, %d, %d },' % (f[0], f[1], k, len(f[2])))
        k += len(f[2])
    print('};')


if __name__ == '__main__':
    main()
